#!/usr/bin/env python3
"""Reads the desktop mode table (app/toolbar.cpp kModes + kGroupNames + kGroupCols) and writes Modes.kt and res/values/modes.xml.
Usage: gen_modes.py [<OnAir repo> <android project>] (default: this checkout and its android/ folder)"""
import re, sys, html, os
_android = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
repo, proj = (sys.argv[1], sys.argv[2]) if len(sys.argv) > 2 else (os.path.dirname(_android), _android)
src = open(os.path.join(repo, 'app/toolbar.cpp'), encoding='utf-8').read()
start = src.index('const ModeDef kModes[] = {')
end = src.index('const int kNumModes')
body = src[start:end]

def split_fields(line):
    # split the top-level commas of "{...}" while honouring strings and parentheses
    line = line.strip()
    assert line.startswith('{') and line.rstrip(',').endswith('}'), line[:60]
    inner = line.rstrip(',')[1:-1]
    out, cur, depth, instr, esc = [], '', 0, False, False
    for ch in inner:
        if instr:
            cur += ch
            if esc: esc = False
            elif ch == '\\': esc = True
            elif ch == '"': instr = False
            continue
        if ch == '"': instr = True; cur += ch; continue
        if ch in '([{': depth += 1
        if ch in ')]}': depth -= 1
        if ch == ',' and depth == 0: out.append(cur.strip()); cur = ''; continue
        cur += ch
    out.append(cur.strip())
    return out

def cstr(s):
    s = s.strip()
    m = re.fullmatch(r'(?:N_|tr)?\(?\s*"((?:[^"\\]|\\.)*)"\s*\)?', s)
    if m is None: return None
    return bytes(m.group(1), 'utf-8').decode('unicode_escape').encode('latin-1', 'ignore').decode('utf-8', 'ignore') if '\\' in m.group(1) else m.group(1)

def vec4(s):
    nums = re.findall(r'-?\d+\.?\d*f?', s)
    r, g, b = [max(0, min(255, round(float(x.rstrip('f')) * 255))) for x in nums[:3]]
    return 0xFF000000 | (r << 16) | (g << 8) | b

modes = []
buf = ''
for line in body.splitlines():
    if not buf and not re.match(r'\s*\{\d+,', line): continue
    buf += line + '\n'
    st = buf.strip()
    if st.endswith('},') and st.count('{') == st.count('}'):
        f = split_fields(buf)
        col = f[3]
        f += ['""'] * (8 - len(f))
        if f[7] in ('""', ''): f[7] = 'ImVec4(0.7f, 0.74f, 0.8f, 1)'
        modes.append(dict(family=int(f[0]), name=cstr(f[1]), group=int(f[2]), blurb=cstr(f[4]) or '', tip=cstr(f[5]) or '', sub=cstr(f[6]) or '', accent=vec4(f[7]),
                          subId=(cstr(f[8]) if len(f) > 8 and f[8] != 'nullptr' else None)))
        buf = ''
gm = re.search(r'kGroupNames\[kNumGroups\]\s*=\s*\{(.*?)\};', src, re.S)
groups = [cstr(x.strip()) for x in re.findall(r'N_\("(?:[^"\\]|\\.)*"\)', gm.group(1))]
groups = [re.match(r'N_\("(.*)"\)', x).group(1) if x and x.startswith('N_') else x for x in re.findall(r'N_\("(?:[^"\\]|\\.)*"\)', gm.group(1))]
cm = re.search(r'kGroupCols\[kNumGroups\]\s*=\s*\{(.*?)\};', src, re.S)
cols = [(int(a) << 16) | (int(b) << 8) | int(c) | 0xFF000000 for a, b, c in re.findall(r'IM_COL32\((\d+),\s*(\d+),\s*(\d+),\s*255\)', cm.group(1))]
assert len(groups) == len(cols), (len(groups), len(cols))
print(len(modes), 'modes', len(groups), 'groups')

def xml(s): return html.escape(s or '', quote=False).replace("'", "\\'").replace('"', '\\"').replace('@', '\\@').replace('?', '\\?')
with open(os.path.join(proj, 'app/src/main/res/values/modes.xml'), 'w', encoding='utf-8') as o:
    o.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_modes.py from the desktop mode table (app/toolbar.cpp). Do not edit. -->\n<resources>\n')
    for i, g in enumerate(groups): o.write(f'    <string name="group_{i}">{xml(g)}</string>\n')
    o.write('    <string-array name="mode_names">\n' + ''.join(f'        <item>{xml(m["name"])}</item>\n' for m in modes) + '    </string-array>\n')
    o.write('    <string-array name="mode_blurbs">\n' + ''.join(f'        <item>{xml(m["blurb"])}</item>\n' for m in modes) + '    </string-array>\n')
    o.write('    <string-array name="mode_subs">\n' + ''.join(f'        <item>{xml(m["sub"])}</item>\n' for m in modes) + '    </string-array>\n')
    o.write('</resources>\n')
with open(os.path.join(proj, 'app/src/main/java/io/github/adswill/onair/Modes.kt'), 'w', encoding='utf-8') as o:
    o.write('// Generated by tools/gen_modes.py from the desktop mode table (app/toolbar.cpp). Do not edit.\npackage io.github.adswill.onair\n\n')
    o.write('/** One row of the desktop table. [family] is the number the desktop stores; [subId] picks a protocol of a shared receiver. */\n')
    o.write('class ModeDef(val index: Int, val family: Int, val group: Int, val accent: Long, val subId: String?)\n\n')
    o.write('object Modes {\n    val groupColors = longArrayOf(' + ', '.join(f'0x{c:08X}' for c in cols) + ')\n    const val GROUPS = %d\n' % len(groups))
    o.write('    val all: List<ModeDef> = listOf(\n')
    for i, m in enumerate(modes):
        sid = f'"{m["subId"]}"' if m['subId'] else 'null'
        o.write(f'        ModeDef({i}, {m["family"]}, {m["group"]}, 0x{m["accent"]:08X}, {sid}),\n')
    o.write('    )\n}\n')
